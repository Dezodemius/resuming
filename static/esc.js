// Общий helper для экранирования пользовательского ввода перед вставкой в innerHTML.
// Резюме, промокоды, имена и email пользователей — не доверенный ввод; часть шаблонов
// подставляет его прямо внутрь HTML-атрибутов (value="${esc(...)}"). Если не экранировать
// кавычки, значение вида `" onfocus="…` вырывается за пределы атрибута и выполняется как
// код — а CSP здесь разрешает 'unsafe-inline', так что это реальный XSS, а не теория.
// Раньше esc() была продублирована в каждом шаблоне и версии разошлись: часть
// экранировала только & < >, не кавычки. Держим одну реализацию тут (issue #47).
function esc(v) {
  return String(v ?? '').replace(/[&<>"']/g, ch => ({
    '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'
  })[ch]);
}
